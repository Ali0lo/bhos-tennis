function buildInitialGroupMatches(groupId: string, players: PlayerProfile[]): GroupMatch[] {
  const matches: GroupMatch[] = [];
  let mIdx = 0;
  for (let i = 0; i < players.length; i++) {
    for (let j = i + 1; j < players.length; j++) {
      matches.push({
        id: `${groupId}-m${mIdx++}`,
        groupId,
        player1: players[i],
        player2: players[j],
        status: 'ready',
      });
    }
  }
  return matches;
}

